type UiCopyOverrides = Partial<Omit<UiCopy, 'deleteHistory' | 'deleteFavorite'>> & {
  deleteHistory?: (sourceText: string) => string;
  deleteFavorite?: (sourceText: string) => string;
  deleteHistoryPrefix?: string;
  deleteFavoritePrefix?: string;
};

function createUiCopy(overrides: UiCopyOverrides): UiCopy {
  const {
    deleteHistory,
    deleteFavorite,
    deleteHistoryPrefix,
    deleteFavoritePrefix,
    ...copy
  } = overrides;

  return {
    ...PRIMARY_UI_COPY.en,
    ...copy,
    deleteHistory:
      deleteHistory ??
      ((sourceText) =>
        (deleteHistoryPrefix ?? PRIMARY_UI_COPY.en.clearHistory) + ': ' + sourceText),
    deleteFavorite:
      deleteFavorite ??
      ((sourceText) =>
        (deleteFavoritePrefix ?? PRIMARY_UI_COPY.en.clearFavorites) + ': ' + sourceText),
  };
}

